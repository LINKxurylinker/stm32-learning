const u16 g_ui_hz16_count = 145;


const UI_HZ16 *UI_HZ16_Find(u16 code)
{
    u16 i;
    for (i = 0; i < g_ui_hz16_count; i++)
    {
        if (g_ui_hz16[i].code == code) return &g_ui_hz16[i];
    }
    return 0;
}

void UI_HZ16_DrawChar(u16 x, u16 y, u16 code, u16 fg, u16 bg)
{
    const UI_HZ16 *g = UI_HZ16_Find(code);
    u8 row, col, byte;
    UI_Fill(x, y, (u16)(x + 15), (u16)(y + 15), bg);
    if (g == 0) return;
    for (row = 0; row < 16; row++)
    {
        for (col = 0; col < 16; col++)
        {
            byte = g->data[col * 2 + row / 8];
            if (byte & (0x80 >> (row & 7)))
                UI_Fill((u16)(x + col), (u16)(y + row),
                        (u16)(x + col), (u16)(y + row), fg);
        }
    }
}

void UI_HZ16_DrawCharScaled(u16 x, u16 y, u16 code,
                            u16 fg, u16 bg, u8 scale)
{
    const UI_HZ16 *g = UI_HZ16_Find(code);
    u8 row, col, byte;
    u16 px, py;
    if (scale == 0) scale = 1;
    for (row = 0; row < 16; row++)
    {
        for (col = 0; col < 16; col++)
        {
            px = (u16)(x + (u16)col * scale);
            py = (u16)(y + (u16)row * scale);
            byte = (g != 0) ? g->data[col * 2 + row / 8] : 0;
            if (byte & (0x80 >> (row & 7)))
                UI_Fill(px, py, (u16)(px + scale - 1), (u16)(py + scale - 1), fg);
            else
                UI_Fill(px, py, (u16)(px + scale - 1), (u16)(py + scale - 1), bg);
        }
    }
}

u16 UI_HZ16_Text(u16 x, u16 y, const char *s, u16 fg, u16 bg)
{
    u16 code;
    while (*s != '\0')
    {
        if ((u8)*s < 0x80)
        {
            FRONT_COLOR = fg; BACK_COLOR = bg;
            LCD_ShowChar(x, y, (u8)*s, 16, 0);
            x = (u16)(x + 8); s++;
        }
        else
        {
            code = (u16)(((u16)(u8)s[0] << 8) | (u16)(u8)s[1]);
            UI_HZ16_DrawChar(x, y, code, fg, bg);
            x = (u16)(x + 16); s += 2;
        }
    }
    return x;
}

u16 UI_HZ16_TextScaled(u16 x, u16 y, const char *s,
                       u16 fg, u16 bg, u8 scale)
{
    u16 code;
    if (scale == 0) scale = 1;
    while (*s != '\0')
    {
        if ((u8)*s < 0x80)
        {
            FRONT_COLOR = fg; BACK_COLOR = bg;
            LCD_ShowChar(x, y, (u8)*s, 16, 0);
            x = (u16)(x + 8 * scale); s++;
        }
        else
        {
            code = (u16)(((u16)(u8)s[0] << 8) | (u16)(u8)s[1]);
            UI_HZ16_DrawCharScaled(x, y, code, fg, bg, scale);
            x = (u16)(x + 16 * scale); s += 2;
        }
    }
    return x;
}
