#define UI_HZ16_COUNT ((u16)(sizeof(g_ui_hz16) / sizeof(g_ui_hz16[0])))

static void ui_hz16_fill(u16 x1, u16 y1, u16 x2, u16 y2, u16 color)
{
    if (x1 > 319U || y1 > 239U) return;
    if (x2 > 319U) x2 = 319U;
    if (y2 > 239U) y2 = 239U;
    LCD_Fill(x1, y1, x2, y2, color);
}

static const ui_hz16 *ui_hz16_find(u16 code)
{
    u16 lo = 0U;
    u16 hi = UI_HZ16_COUNT;

    while (lo < hi)
    {
        u16 mid = (u16)((lo + hi) / 2U);
        if (g_ui_hz16[mid].code == code) return &g_ui_hz16[mid];
        if (g_ui_hz16[mid].code < code) lo = (u16)(mid + 1U);
        else                            hi = mid;
    }
    return 0;
}

static void ui_hz16_draw(u16 x, u16 y, u16 code, u16 fg, u16 bg)
{
    const ui_hz16 *g = ui_hz16_find(code);
    u8  row;
    u8  col;
    u8  start;
    u8  byte;

    ui_hz16_fill(x, y, (u16)(x + 15U), (u16)(y + 15U), bg);
    if (g == 0) return;

    for (row = 0U; row < 16U; row++)
    {
        col = 0U;
        while (col < 16U)
        {
            byte = g->data[col * 2U + row / 8U];
            if ((byte & (u8)(0x80U >> (row & 7U))) == 0U)
            {
                col++;
                continue;
            }
            start = col;
            while (col < 16U)
            {
                byte = g->data[col * 2U + row / 8U];
                if ((byte & (u8)(0x80U >> (row & 7U))) == 0U) break;
                col++;
            }
            ui_hz16_fill((u16)(x + start), (u16)(y + row),
                         (u16)(x + col - 1U), (u16)(y + row), fg);
        }
    }
}

/* 16px mixed text: ASCII 8 wide, Chinese 16 wide. Returns end x. */
static u16 ui_hz16_text(u16 x, u16 y, const char *s, u16 fg, u16 bg)
{
    u16 code;

    while (*s != 0)
    {
        if ((u8)*s < 0x80U)
        {
            POINT_COLOR = fg;
            BACK_COLOR  = bg;
            LCD_ShowChar(x, y, (u8)*s, 16, 0);
            x = (u16)(x + 8U);
            s++;
        }
        else
        {
            code = (u16)(((u16)(u8)s[0] << 8) | (u16)(u8)s[1]);
            ui_hz16_draw(x, y, code, fg, bg);
            x = (u16)(x + 16U);
            s += 2;
        }
    }
    return x;
}

static u16 ui_hz16_width(const char *s)
{
    u16 w = 0U;

    while (*s != 0)
    {
        if ((u8)*s < 0x80U) { w = (u16)(w + 8U); s++; }
        else                { w = (u16)(w + 16U); s += 2; }
    }
    return w;
}

